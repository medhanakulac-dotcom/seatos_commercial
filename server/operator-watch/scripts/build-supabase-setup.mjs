// Writes supabase/setup.sql: everything Operator Watch needs in the site's Supabase project, in one file to paste
// into the SQL editor. Re-run after adding a migration (node server/operator-watch/scripts/build-supabase-setup.mjs);
// the file is safe to run again — finished steps and applied migrations are skipped.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrations = readdirSync(join(root, 'migrations'))
  .filter((f) => /^\d+_.+\.sql$/.test(f))
  .sort();

const applyMigration = (file) => {
  const sql = readFileSync(join(root, 'migrations', file), 'utf8').trim();
  if (sql.includes('$ow_migration$')) throw new Error(`${file} contains the dollar-quote tag used to wrap it`);
  return `do $ow$
begin
  if not exists (select 1 from operator_watch.schema_migrations where name = '${file}') then
    execute $ow_migration$
${sql}
$ow_migration$;
    insert into operator_watch.schema_migrations (name) values ('${file}');
    raise notice 'Applied ${file}';
  end if;
end
$ow$;`;
};

const out = `-- Operator Watch: Supabase setup (generated by server/operator-watch/scripts/build-supabase-setup.mjs — do not edit).
--
-- Run in Supabase → SQL editor, in the site's project. Safe to run again.
-- Before running, replace the two placeholders below:
--   CHANGE_ME_DB_PASSWORD  a new strong password for the operator_watch database role (goes into DATABASE_URL)
--   CHANGE_ME_SITE_URL     the site's production URL, e.g. https://seatos-commercial.vercel.app (no trailing slash)
-- and store the cron secret in Vault (step 4) with the same value as the CRON_SECRET env var on Vercel.

-- 1. A login role that owns a private schema. The API connects as this role, so it can only see its own tables
--    (plus read access to public.allowed_users). The schema is not exposed through the Supabase REST API.
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'operator_watch') then
    create role operator_watch login password 'CHANGE_ME_DB_PASSWORD';
  end if;
end
$$;
grant operator_watch to postgres;
create schema if not exists operator_watch authorization operator_watch;
alter role operator_watch set search_path = operator_watch;
grant usage on schema public to operator_watch;
grant select on public.allowed_users to operator_watch;

-- 2. Tables, created as operator_watch so it owns them.
set role operator_watch;
set search_path = operator_watch;
create table if not exists operator_watch.schema_migrations (name text primary key, applied_at timestamptz not null default now());

${migrations.map(applyMigration).join('\n\n')}

reset role;
reset search_path;

-- 3. Scheduler: call the API's tick every minute (opens due runs, sends due emails).
create extension if not exists pg_cron;
create extension if not exists pg_net;

-- 4. The cron secret, kept in Vault rather than in the job text. Run once with your value (same as CRON_SECRET on Vercel):
--      select vault.create_secret('<the CRON_SECRET value>', 'operator_watch_cron_secret');
--    To change it later: select vault.update_secret((select id from vault.secrets where name = 'operator_watch_cron_secret'), '<new value>');

select cron.unschedule(jobid) from cron.job where jobname = 'operator-watch-tick';
select cron.schedule(
  'operator-watch-tick',
  '* * * * *',
  $cron$
  select net.http_post(
    url := 'CHANGE_ME_SITE_URL/api/ow/internal/tick',
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || (select decrypted_secret from vault.decrypted_secrets where name = 'operator_watch_cron_secret')
    ),
    body := '{}'::jsonb,
    timeout_milliseconds := 55000
  );
  $cron$
);
`;

mkdirSync(join(root, 'supabase'), { recursive: true });
writeFileSync(join(root, 'supabase', 'setup.sql'), out);
console.log(`supabase/setup.sql written (${migrations.length} migrations)`);
